#!/usr/bin/env node
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { load } from 'js-yaml';

const meta = load(readFileSync('metadata.yaml', 'utf8'));
const folders = { paintings: 'paintings', works_on_paper: 'works-on-paper', sculpture: 'sculpture' };
if (!meta || typeof meta !== 'object' || Array.isArray(meta)) throw new Error('metadata.yaml must contain artwork sections.');
for (const section of Object.keys(meta)) {
  if (!(section in folders)) throw new Error(`Unknown metadata section: ${section}`);
}
const artworks = {};
for (const [section, folder] of Object.entries(folders)) {
  const works = meta[section] ?? [];
  if (!Array.isArray(works)) throw new Error(`${section} must be a list of artworks.`);
  const slugs = new Set();
  artworks[folder] = works.map((work, index) => {
    if (!work || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(work.slug ?? '')) throw new Error(`${section} artwork ${index + 1}: invalid slug.`);
    if (slugs.has(work.slug)) throw new Error(`${section}: duplicate slug ${work.slug}`);
    slugs.add(work.slug);
    if (typeof work.title !== 'string' || !work.title.trim()) throw new Error(`${work.slug}: title is required.`);
    if (work.year != null && !Number.isInteger(work.year)) throw new Error(`${work.slug}: year must be an integer or null.`);
    for (const field of ['medium', 'dimensions']) {
      if (work[field] != null && typeof work[field] !== 'string') throw new Error(`${work.slug}: ${field} must be text.`);
    }
    const img = `images/${folder}/web/${work.slug}.jpg`;
    const thumb = `images/${folder}/thumbs/${work.slug}.jpg`;
    for (const file of [img, thumb]) {
      if (!existsSync(file)) throw new Error(`Missing ${file}. Upload the original and run npm run images.`);
    }
    return { id: `${section[0]}${index + 1}`, slug: work.slug, title: work.title,
      year: work.year ?? null, medium: folder, dims: work.dimensions ?? '',
      materials: work.medium ?? '', img, thumb };
  });
}
writeFileSync('js/data.js', '// AUTO-GENERATED by build.js — do not edit by hand.\n// Edit metadata.yaml instead, then run npm run build.\n\nconst artworks = ' + JSON.stringify(artworks, null, 2) + ';\n');
console.log('Built and validated js/data.js from metadata.yaml');
